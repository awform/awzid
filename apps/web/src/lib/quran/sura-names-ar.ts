/** Titre du bandeau : « سورة » + nom (sans voyelles, comme la source). */
export const suraTitleAr = (s: number) => `سورة ${SURA_NAMES_AR[s - 1] ?? ''}`;

const DIGITS = '٠١٢٣٤٥٦٧٨٩';
/** Numéro de verset en chiffres arabo-indiens précédé du signe de fin de verset ۝ (ornement, hors texte). */
export const ayaNumberAr = (a: number) =>
  '\u06DD' + String(a).replace(/\d/g, (d) => DIGITS[Number(d)]!);

