<h1>Coran</h1>
<p class="muted">
  Lecture (qāʿida), mémorisation (hifẓ) et lecteur coranique. Riwāya Ḥafṣ ʿan ʿĀṣim, texte Tanzil
  exact.
</p>

<section class="card">
  <h2>Hifẓ — mon carnet <span class="soon">lot 5</span></h2>
  <p>
    Carnets E1 (Enfants) et N1 (Adultes) : plan de l'année, trois pistes chaque jour (nouveau,
    récent, ancien), révisions à J+1, J+2, J+3, J+7, J+14, J+30, validation d'entraînement par le
    parent. Le maître reste le seul juge ; aucune ijāza.
  </p>
</section>

<section class="card">
  <h2>Lecteur coranique <span class="soon">en préparation</span></h2>
  <ul>
    <li>choix du récitant (uniquement des récitations sous licence écrite) ;</li>
    <li>lecture verset par verset, surlignage mot à mot ;</li>
    <li>répétition d'un verset ou d'une plage N fois, avec pause « je répète » ;</li>
    <li>vitesse réglable ; page du Muṣḥaf de Médine ;</li>
    <li>téléchargement par sourate pour écouter sans réseau.</li>
  </ul>
  <p class="muted">
    Aucun audio sans licence : le lecteur sera prêt, les voix seront ajoutées quand les droits
    seront acquis.
  </p>
</section>

